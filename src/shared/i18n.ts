export type TranslationKey = keyof typeof TRANSLATIONS.en;

export function t(lang: Language, key: TranslationKey): string {
  return TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key];
}

export function unitLabel(lang: Language, unit: SoldByUnit): string {
  const map: Record<SoldByUnit, TranslationKey> = {
    bottle: 'unit_bottle',
    can: 'unit_can',
    case: 'unit_case',
    pack: 'unit_pack',
    unit: 'unit_unit',
  };
  return t(lang, map[unit] ?? 'unit_unit');
}

export function roleLabel(lang: Language, role: StaffRole): string {
  const map: Record<StaffRole, TranslationKey> = {
    owner: 'role_owner',
    manager: 'role_manager',
    employee: 'role_employee',
  };
  return t(lang, map[role]);
}

export function methodLabel(lang: Language, method: PaymentMethod): string {
  return method === 'bank_transfer'
    ? t(lang, 'method_bank_transfer')
    : t(lang, 'method_cash');
}

export function localizedName(lang: Language, nameEn: string, nameTa?: string | null): string {
  if (lang === 'ta' && nameTa && nameTa.trim()) return nameTa.trim();
  return nameEn;
}
